#!/usr/bin/env python3
"""Generate prisma/schema.prisma for the benchmark tables (models map onto the existing tables; no migrations)."""
import os
MIX = ["Int", "BigInt", "Decimal @db.Decimal(15, 2)", "Float @db.Double", "String @db.VarChar(32)", "DateTime @db.DateTime(6)",
       "DateTime @db.Date", "Int @db.TinyInt", "String? @db.VarChar(255)", "Int?"]


def wide(name, table, types):
    cols = "\n".join(f"  c{k:03d} {t}" for k, t in enumerate(types, 1))
    return f"model {name} {{\n  id Int @id\n{cols}\n  @@map(\"{table}\")\n}}\n"


schema = '''// Generated by gen_prisma.py. Models map onto the existing benchmark tables.
generator client {
  provider = "prisma-client-js"
  output   = "../prisma-client"
}

datasource db {
  provider = "mysql"
}

model TInt {
  id Int @id
  v  Int
  @@map("t_int")
}

model TBlob {
  id         Int    @id
  size_class String @db.VarChar(8)
  doc        String @db.LongText
  doc_bin    Bytes  @db.LongBlob
  @@map("t_blob")
}

model TBulk {
  id Int    @id
  a  Int
  b  String @db.VarChar(32)
  c  Float  @db.Double
  @@map("t_bulk")
}

''' + wide("WideInt", "t_wide_int", ["Int"] * 100) + "\n" + wide("WideMix", "t_wide_mix", [MIX[(k - 1) % 10] for k in range(1, 101)])
d = os.path.join(os.path.dirname(__file__), "prisma")
os.makedirs(d, exist_ok=True)
open(os.path.join(d, "schema.prisma"), "w").write(schema)
print("generated prisma/schema.prisma")
