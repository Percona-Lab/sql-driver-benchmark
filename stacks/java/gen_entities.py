#!/usr/bin/env python3
"""Generate the JPA entities for the 100-column tables (t_wide_int, t_wide_mix) used by the Hibernate runner."""
import os
OUT = os.path.join(os.path.dirname(__file__), "src/main/java/bench/fw")
os.makedirs(OUT, exist_ok=True)
MIX = [("Integer", "INT"), ("Long", "BIGINT"), ("java.math.BigDecimal", "DECIMAL"), ("Double", "DOUBLE"), ("String", "VARCHAR32"),
       ("java.time.LocalDateTime", "DATETIME"), ("java.time.LocalDate", "DATE"), ("Byte", "TINYINT"), ("String", "VARCHAR255"),
       ("Integer", "INTN")]


def entity(cls, table, types):
    f = "\n".join(f'    @Column(name = "c{k:03d}") public {t} c{k:03d};' for k, t in enumerate(types, 1))
    vals = ", ".join(f"c{k:03d}" for k in range(1, len(types) + 1))
    return f'''package bench.fw;

import jakarta.persistence.*;

/** Generated by gen_entities.py: mapping of {table} (100 columns). */
@Entity @Table(name = "{table}")
public class {cls} {{
    @Id public Integer id;
{f}
    /** All column values after id, in table order (used by the touch loop). */
    public Object[] values() {{ return new Object[]{{{vals}}}; }}
}}
'''


open(f"{OUT}/WideInt.java", "w").write(entity("WideInt", "t_wide_int", ["Integer"] * 100))
open(f"{OUT}/WideMix.java", "w").write(entity("WideMix", "t_wide_mix", [MIX[(k - 1) % 10][0] for k in range(1, 101)]))
print("generated WideInt.java, WideMix.java")
