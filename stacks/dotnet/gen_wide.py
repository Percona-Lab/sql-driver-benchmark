#!/usr/bin/env python3
"""Generate the C# entity classes for the 100-column tables (EF Core + Dapper map them by property name)."""
import os
MIX = ["int", "long", "decimal", "double", "string", "DateTime", "DateTime", "sbyte", "string?", "int?"]


def cls(name, table, types):
    props = "\n".join(f"    public {t} c{k:03d} {{ get; set; }}" + (" = \"\";" if t == "string" else "") for k, t in enumerate(types, 1))
    vals = ", ".join(f"c{k:03d}" for k in range(1, len(types) + 1))
    return f'''
[Table("{table}")]
public class {name}
{{
    [Key, DatabaseGenerated(DatabaseGeneratedOption.None)] public int id {{ get; set; }}
{props}
    public object?[] Values() => new object?[] {{ {vals} }};
}}
'''


src = ("// Generated by gen_wide.py.\n#nullable enable\nusing System.ComponentModel.DataAnnotations;\n"
       "using System.ComponentModel.DataAnnotations.Schema;\n")
src += cls("WideInt", "t_wide_int", ["int"] * 100)
src += cls("WideMix", "t_wide_mix", [MIX[(k - 1) % 10] for k in range(1, 101)])
open(os.path.join(os.path.dirname(__file__), "WideGen.cs"), "w").write(src)
print("generated WideGen.cs")
