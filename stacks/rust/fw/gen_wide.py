#!/usr/bin/env python3
"""Generate the 100-column table mappings for the Rust framework runner: Diesel table!/Queryable and SeaORM entities.

Column types follow orchestrator/load.py (TYPES). touch() applies the same rule as every other runner: count non-NULL
values, add integer values, add string lengths; DECIMAL, DOUBLE, DATE and DATETIME are decoded but not added.
"""
import os

#        Diesel SQL type          Diesel Rust type          SeaORM Rust type      touch
MIX = [("Integer",               "i32",                    "i32",                "int"),
       ("BigInt",                "i64",                    "i64",                "int"),
       ("Numeric",               "bigdecimal::BigDecimal", "Decimal",            "-"),
       ("Double",                "f64",                    "f64",                "-"),
       ("Varchar",               "String",                 "String",             "str"),
       ("Datetime",              "chrono::NaiveDateTime",  "DateTime",           "-"),
       ("Date",                  "chrono::NaiveDate",      "Date",               "-"),
       ("TinyInt",               "i8",                     "i8",                 "int"),
       ("Nullable<Varchar>",     "Option<String>",         "Option<String>",     "ostr"),
       ("Nullable<Integer>",     "Option<i32>",            "Option<i32>",        "oint")]
INT = ("Integer", "i32", "i32", "int")


def touch_expr(k, kind):
    f = f"self.c{k:03d}"
    return {"int": f"nn += 1; isum += {f} as i64;", "str": f"nn += 1; slen += {f}.len() as i64;",
            "-": f"nn += 1; std::hint::black_box(&{f});",
            "ostr": f"if let Some(v) = &{f} {{ nn += 1; slen += v.len() as i64; }}",
            "oint": f"if let Some(v) = {f} {{ nn += 1; isum += v as i64; }}"}[kind]


def tables(name, table, types):
    cols = "\n".join(f"        c{k:03d} -> {t[0]}," for k, t in enumerate(types, 1))
    dfields = "\n".join(f"    pub c{k:03d}: {t[1]}," for k, t in enumerate(types, 1))
    sfields = "\n".join(f"        pub c{k:03d}: {t[2]}," for k, t in enumerate(types, 1))
    touch = "\n".join(f"        {touch_expr(k, t[3])}" for k, t in enumerate(types, 1))
    stouch = touch.replace("        ", "            ")
    mod = table
    return f'''
// ---- {table}
pub mod d_{mod} {{
    diesel::table! {{
        {table} (id) {{
        id -> Integer,
{cols}
        }}
    }}
}}
#[derive(diesel::Queryable, diesel::Selectable)]
#[diesel(table_name = d_{mod}::{table}, check_for_backend(diesel::mysql::Mysql))]
pub struct {name} {{
    pub id: i32,
{dfields}
}}
impl {name} {{
    pub fn touch(&self) -> (i64, i64, i64) {{
        let (mut nn, mut isum, mut slen) = (0i64, 0i64, 0i64);
{touch}
        (nn, isum, slen)
    }}
}}
pub mod s_{mod} {{
    use sea_orm::entity::prelude::*;
    #[derive(Clone, Debug, PartialEq, DeriveEntityModel)]
    #[sea_orm(table_name = "{table}")]
    pub struct Model {{
        #[sea_orm(primary_key, auto_increment = false)]
        pub id: i32,
{sfields}
    }}
    #[derive(Copy, Clone, Debug, EnumIter, DeriveRelation)]
    pub enum Relation {{}}
    impl ActiveModelBehavior for ActiveModel {{}}
    impl Model {{
        pub fn touch(&self) -> (i64, i64, i64) {{
            let (mut nn, mut isum, mut slen) = (0i64, 0i64, 0i64);
{stouch}
            (nn, isum, slen)
        }}
    }}
}}
'''


src = "// Generated by gen_wide.py. DO NOT EDIT.\n#![allow(clippy::all)]\n"
src += tables("DWideInt", "t_wide_int", [INT] * 100)
src += tables("DWideMix", "t_wide_mix", [MIX[(k - 1) % 10] for k in range(1, 101)])
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "src", "wide.rs"), "w").write(src)
print("generated src/wide.rs")
