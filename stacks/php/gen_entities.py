#!/usr/bin/env python3
"""Generate Doctrine ORM entities (PHP attributes) for the benchmark tables."""
import os
OUT = os.path.join(os.path.dirname(__file__), "entities")
os.makedirs(OUT, exist_ok=True)
MIX = [("int", "integer", ""), ("int", "bigint", ""), ("string", "decimal", ", precision: 15, scale: 2"), ("float", "float", ""),
       ("string", "string", ", length: 32"), ("\\DateTime", "datetime", ""), ("\\DateTime", "date", ""), ("int", "smallint", ""),
       ("?string", "string", ", length: 255, nullable: true"), ("?int", "integer", ", nullable: true")]


def entity(cls, table, cols):
    fields = "\n".join(f"    #[ORM\\Column(name: '{n}', type: '{t}'{x})] public {php} ${n};" for n, php, t, x in cols)
    return f"""<?php
// Generated by gen_entities.py.
namespace Bench;
use Doctrine\\ORM\\Mapping as ORM;

#[ORM\\Entity, ORM\\Table(name: '{table}')]
class {cls}
{{
    #[ORM\\Id, ORM\\Column(type: 'integer')] public int $id;
{fields}
}}
"""


ents = {
    "TInt": ("t_int", [("v", "int", "integer", "")]),
    "TBlob": ("t_blob", [("size_class", "string", "string", ", length: 8"), ("doc", "string", "text", ""), ("doc_bin", "mixed", "blob", "")]),
    "TBulk": ("t_bulk", [("a", "int", "integer", ""), ("b", "string", "string", ", length: 32"), ("c", "float", "float", "")]),
    "WideInt": ("t_wide_int", [(f"c{k:03d}", "int", "integer", "") for k in range(1, 101)]),
    "WideMix": ("t_wide_mix", [(f"c{k:03d}", MIX[(k - 1) % 10][0], MIX[(k - 1) % 10][1], MIX[(k - 1) % 10][2]) for k in range(1, 101)]),
}
for cls, (table, cols) in ents.items():
    open(os.path.join(OUT, f"{cls}.php"), "w").write(entity(cls, table, cols))
print("generated", ", ".join(ents))
